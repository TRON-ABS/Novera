import { afterEach, describe, expect, it, vi } from 'vitest'
import { VoiceConversation, spokenText, type VoiceBackend, type VoiceBinding, type VoiceRecognition } from '../voiceConversation'

function deferred<T>() {
  let resolve!: (value: T) => void
  let reject!: (error: Error) => void
  const promise = new Promise<T>((yes, no) => { resolve = yes; reject = no })
  return { promise, resolve, reject }
}
const flush = async () => { await Promise.resolve(); await Promise.resolve(); await Promise.resolve() }
const sessions: VoiceConversation[] = []
afterEach(() => { sessions.forEach(session => session.stop()); sessions.length = 0; vi.useRealTimers() })
function fixture(overrides: Partial<VoiceBinding> = {}) {
  const listen = deferred<VoiceRecognition>()
  const speak = deferred<void>()
  const backend: VoiceBackend = {
    listen: vi.fn().mockReturnValueOnce(listen.promise).mockImplementation(() => new Promise(() => {})),
    speak: vi.fn(() => speak.promise), stop: vi.fn(),
  }
  const binding: VoiceBinding = {
    scope: 'thread-1', isNew: false, busy: false, failed: false, canStart: true,
    replyId: 'old', reply: 'Do not read this old reply', lastUserText: '',
    submit: vi.fn(async () => {}), error: vi.fn(), ...overrides,
  }
  const session = new VoiceConversation(); sessions.push(session)
  return { session, binding, backend, listen, speak }
}

